//! Windows exception, unwind and x86-family context constants.

pub const EXCEPTION_CONTINUE_EXECUTION32: u32 = 0xffff_ffff;
pub const EXCEPTION_CONTINUE_EXECUTION64: u64 = 0xffff_ffff_ffff_ffff;
pub const EXCEPTION_CONTINUE_SEARCH: u32 = 0;
pub const EXCEPTION_EXECUTE_HANDLER: u32 = 1;

#[derive(Clone, Copy, Debug, PartialEq, Eq)]
#[repr(u32)]
pub enum ExceptionDisposition {
    ContinueExecution = 0,
    ContinueSearch = 1,
    NestedException = 2,
    CollidedUnwind = 3,
}

pub const CALL_FIRST: u32 = 1;
pub const CALL_LAST: u32 = 0;

pub const EXCEPTION_READ_FAULT: u64 = 0;
