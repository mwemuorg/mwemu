pub(crate) fn dispatch(api: &str, emu: &mut Emu) -> bool {
    dispatch_sid(api, "advapi32", emu)
        || registry::gateway(api, emu)
        || accounts::dispatch(api, emu)
        || crypto::dispatch(api, emu)
        || registry_api::dispatch(api, emu)
        || security::dispatch(api, emu)
        || services::dispatch(api, emu)
        || system::dispatch(api, emu)
        || tokens::dispatch(api, emu)
        || tracing::dispatch(api, emu)
}

