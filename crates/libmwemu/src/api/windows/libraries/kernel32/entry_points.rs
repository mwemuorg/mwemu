//! Rust entry points shared by both guest architectures. The DLL name identifies the provider when a caller invokes a handler outside a gateway.
macro_rules! kernel_entry_points {
    ($library:literal; $($name:ident),+ $(,)?) => {$(
        pub fn $name(emu: &mut $crate::emu::Emu) {
            $crate::winapi::libraries::kernel32::dispatch_shared(stringify!($name), $library, emu);
        }
    )+};
}

