use crate::emu;
use crate::winapi::helper::WinApiAbi;
use crate::windows::constants::system::*;

pub fn IsProcessorFeaturePresent(emu: &mut emu::Emu) {
    let feature = WinApiAbi::arg(emu, 0) as u32;
    emu.stack_pop32(false);

    let msg = match feature {
        PF_ARM_64BIT_LOADSTORE_ATOMIC => "PF_ARM_64BIT_LOADSTORE_ATOMIC",
        PF_ARM_DIVIDE_INSTRUCTION_AVAILABLE => "PF_ARM_DIVIDE_INSTRUCTION_AVAILABLE",
        PF_ARM_EXTERNAL_CACHE_AVAILABLE => "PF_ARM_EXTERNAL_CACHE_AVAILABLE",
        PF_ARM_FMAC_INSTRUCTIONS_AVAILABLE => "PF_ARM_FMAC_INSTRUCTIONS_AVAILABLE",
        PF_ARM_VFP_32_REGISTERS_AVAILABLE => "PF_ARM_VFP_32_REGISTERS_AVAILABLE",
        PF_3DNOW_INSTRUCTIONS_AVAILABLE => "PF_3DNOW_INSTRUCTIONS_AVAILABLE",
        PF_CHANNELS_ENABLED => "PF_CHANNELS_ENABLED",
        PF_COMPARE_EXCHANGE_DOUBLE => "PF_COMPARE_EXCHANGE_DOUBLE",
        PF_COMPARE_EXCHANGE128 => "PF_COMPARE_EXCHANGE128",
        PF_COMPARE64_EXCHANGE128 => "PF_COMPARE64_EXCHANGE128",
        PF_FASTFAIL_AVAILABLE => "PF_FASTFAIL_AVAILABLE",
        PF_FLOATING_POINT_EMULATED => "PF_FLOATING_POINT_EMULATED",
        PF_FLOATING_POINT_PRECISION_ERRATA => "PF_FLOATING_POINT_PRECISION_ERRATA",
        PF_MMX_INSTRUCTIONS_AVAILABLE => "PF_MMX_INSTRUCTIONS_AVAILABLE",
        PF_NX_ENABLED => "PF_NX_ENABLED",
        PF_PAE_ENABLED => "PF_PAE_ENABLED",
        PF_RDTSC_INSTRUCTION_AVAILABLE => "PF_RDTSC_INSTRUCTION_AVAILABLE",
        PF_RDWRFSGSBASE_AVAILABLE => "PF_RDWRFSGSBASE_AVAILABLE",
        PF_SECOND_LEVEL_ADDRESS_TRANSLATION => "PF_SECOND_LEVEL_ADDRESS_TRANSLATION",
        PF_SSE3_INSTRUCTIONS_AVAILABLE => "PF_SSE3_INSTRUCTIONS_AVAILABLE",
        PF_SSSE3_INSTRUCTIONS_AVAILABLE => "PF_SSSE3_INSTRUCTIONS_AVAILABLE",
        PF_SSE4_1_INSTRUCTIONS_AVAILABLE => "PF_SSE4_1_INSTRUCTIONS_AVAILABLE",
        PF_SSE4_2_INSTRUCTIONS_AVAILABLE => "PF_SSE4_2_INSTRUCTIONS_AVAILABLE",
        PF_AVX_INSTRUCTIONS_AVAILABLE => "PF_AVX_INSTRUCTIONS_AVAILABLE",
        PF_AVX2_INSTRUCTIONS_AVAILABLE => "PF_AVX2_INSTRUCTIONS_AVAILABLE",
        PF_AVX512F_INSTRUCTIONS_AVAILABLE => "PF_AVX512F_INSTRUCTIONS_AVAILABLE",
        PF_VIRT_FIRMWARE_ENABLED => "PF_VIRT_FIRMWARE_ENABLED",
        PF_XMMI_INSTRUCTIONS_AVAILABLE => "PF_XMMI_INSTRUCTIONS_AVAILABLE",
        PF_XMMI64_INSTRUCTIONS_AVAILABLE => "PF_XMMI64_INSTRUCTIONS_AVAILABLE",
        PF_XSAVE_ENABLED => "PF_XSAVE_ENABLED",
        PF_ARM_V8_INSTRUCTIONS_AVAILABLE => "PF_ARM_V8_INSTRUCTIONS_AVAILABLE",
        PF_ARM_V8_CRYPTO_INSTRUCTIONS_AVAILABLE => "PF_ARM_V8_CRYPTO_INSTRUCTIONS_AVAILABLE",
        PF_ARM_V8_CRC32_INSTRUCTIONS_AVAILABLE => "PF_ARM_V8_CRC32_INSTRUCTIONS_AVAILABLE",
        PF_ARM_V81_ATOMIC_INSTRUCTIONS_AVAILABLE => "PF_ARM_V81_ATOMIC_INSTRUCTIONS_AVAILABLE",
        _ => "unknown feature",
    };

    log_red!(
        emu,
        "kernel32!IsProcessorFeaturePresent feature: {} {}",
        feature,
        msg
    );

    emu.regs_mut().rax = 1;
}
