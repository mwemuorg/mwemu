use crate::emu;

pub fn BaseFormatObjectAttributes(emu: &mut emu::Emu) {
    let param1 = emu.regs().rcx;
    let param2 = emu.regs().rdx;
    log_red!(
        emu,
        "kernel32!BaseFormatObjectAttributes param1:0x{:x} param2:0x{:x}",
        param1,
        param2
    );
    let src = emu.regs().rcx;
    if src != 0 && emu.maps.is_mapped(src) {
        let _input = emu.maps.read_string(src);
    }
    emu.set_last_error(0);
    emu.regs_mut().rax = 0;
}
