use crate::emu;
use crate::winapi::helper;
use crate::windows::constants;
pub fn LoadStringBaseW(emu: &mut emu::Emu) {
    let _a1 = emu.regs().rcx as u32;
    let _a2 = emu.regs().rdx as u32;
    let _a3 = emu.regs().r8 as u32;
    let _a4 = emu.regs().r9 as u32;
    log_red!(emu, "kernel32!LoadStringBaseW");
    let handle = helper::handler_create("LoadStringBaseW");
    let out_ptr = emu.regs().r9;
    if out_ptr != 0 {
        emu.maps.write_qword(out_ptr, handle);
    }
    emu.set_last_error(0);
    emu.regs_mut().rax = constants::ERROR_SUCCESS;
}
