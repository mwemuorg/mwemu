use crate::api::dispatch_api;
use crate::emu::Emu;
use crate::winapi::winapi64::kernelbase;

pub(super) fn dispatch(api: &str, addr: u64, emu: &mut Emu) -> bool {
    dispatch_api!(api, {
        "LoadStringA" => kernelbase::LoadStringA(emu),
        "LoadStringW" => kernelbase::LoadStringW(emu),
        "EnumSystemGeoID" => kernelbase::EnumSystemGeoID(emu),
        "EnumSystemGeoNames" => kernelbase::EnumSystemGeoNames(emu),
        "GetACP" => kernelbase::GetACP(emu),
        "GetCPInfo" => kernelbase::GetCPInfo(emu),
        "GetGeoInfoEx" => kernelbase::GetGeoInfoEx(emu),
        "GetLocaleInfoA" => kernelbase::GetLocaleInfoA(emu),
        "GetLocaleInfoEx" => kernelbase::GetLocaleInfoEx(emu),
        "GetLocaleInfoW" => kernelbase::GetLocaleInfoW(emu),
        "GetLogicalDriveStringsW" => kernelbase::GetLogicalDriveStringsW(emu),
        "GetOEMCP" => kernelbase::GetOEMCP(emu),
        "GetStringTypeA" => kernelbase::GetStringTypeA(emu),
        "GetStringTypeW" => kernelbase::GetStringTypeW(emu),
        "GetUserDefaultGeoName" => kernelbase::GetUserDefaultGeoName(emu),
        "GetUserDefaultLCID" => kernelbase::GetUserDefaultLCID(emu),
        "GetUserDefaultLangID" => kernelbase::GetUserDefaultLangID(emu),
        "GetUserDefaultUILanguage" => kernelbase::GetUserDefaultUILanguage(emu),
        "GetUserGeoID" => kernelbase::GetUserGeoID(emu),
        "IsValidCodePage" => kernelbase::IsValidCodePage(emu),
        "IsValidLocale" => kernelbase::IsValidLocale(emu),
        "LCMapStringA" => kernelbase::LCMapStringA(emu),
        "LCMapStringW" => kernelbase::LCMapStringW(emu),
        "MultiByteToWideChar" => kernelbase::MultiByteToWideChar(emu),
        "SetLocaleInfoW" => kernelbase::SetLocaleInfoW(emu),
        "SetUserGeoID" => kernelbase::SetUserGeoID(emu),
        "SetUserGeoName" => kernelbase::SetUserGeoName(emu),
        "WideCharToMultiByte" => kernelbase::WideCharToMultiByte(emu),
        "lstrcmp" => kernelbase::lstrcmp(emu),
        "lstrcmpA" => kernelbase::lstrcmpA(emu),
        "lstrcmpW" => kernelbase::lstrcmpW(emu),
        "lstrcmpi" => kernelbase::lstrcmpi(emu),
        "lstrcmpiA" => kernelbase::lstrcmpiA(emu),
        "lstrcmpiW" => kernelbase::lstrcmpiW(emu),
        "lstrcpyn" => kernelbase::lstrcpyn(emu),
        "lstrcpynA" => kernelbase::lstrcpynA(emu),
        "lstrcpynW" => kernelbase::lstrcpynW(emu),
        "lstrlen" => kernelbase::lstrlen(emu),
        "lstrlenA" => kernelbase::lstrlenA(emu),
        "lstrlenW" => kernelbase::lstrlenW(emu),
    },
        handled(()) => true,
        fallback => false,
    )
}
