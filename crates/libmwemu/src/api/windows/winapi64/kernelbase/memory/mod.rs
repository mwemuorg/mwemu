use crate::api::dispatch_api;
use crate::emu::Emu;
use crate::winapi::winapi64::kernelbase;

pub(super) fn dispatch(api: &str, addr: u64, emu: &mut Emu) -> bool {
    dispatch_api!(api, {
        "LocalAlloc" => kernelbase::LocalAlloc(emu),
        "CopyMemoryNonTemporal" => kernelbase::CopyMemoryNonTemporal(emu),
        "DecodeRemotePointer" => kernelbase::DecodeRemotePointer(emu),
        "EncodeRemotePointer" => kernelbase::EncodeRemotePointer(emu),
        "MapViewOfFile3" => kernelbase::MapViewOfFile3(emu),
        "MapViewOfFile3FromApp" => kernelbase::MapViewOfFile3FromApp(emu),
        "MapViewOfFileNuma2" => kernelbase::MapViewOfFileNuma2(emu),
        "UnmapViewOfFile2" => kernelbase::UnmapViewOfFile2(emu),
        "VirtualAllocFromApp" => kernelbase::VirtualAllocFromApp(emu),
        "VirtualProtectFromApp" => kernelbase::VirtualProtectFromApp(emu),
        "CreateEnclave" => kernelbase::CreateEnclave(emu),
        "DecodePointer" => kernelbase::DecodePointer(emu),
        "DecodeSystemPointer" => kernelbase::DecodeSystemPointer(emu),
        "DiscardVirtualMemory" => kernelbase::DiscardVirtualMemory(emu),
        "EncodePointer" => kernelbase::EncodePointer(emu),
        "EncodeSystemPointer" => kernelbase::EncodeSystemPointer(emu),
        "FlushInstructionCache" => kernelbase::FlushInstructionCache(emu),
        "FlushViewOfFile" => kernelbase::FlushViewOfFile(emu),
        "GetProcessHeap" => kernelbase::GetProcessHeap(emu),
        "GetProcessHeaps" => kernelbase::GetProcessHeaps(emu),
        "GetProcessWorkingSetSize" => kernelbase::GetProcessWorkingSetSize(emu),
        "GlobalAlloc" => kernelbase::GlobalAlloc(emu),
        "GlobalFlags" => kernelbase::GlobalFlags(emu),
        "GlobalFree" => kernelbase::GlobalFree(emu),
        "GlobalLock" => kernelbase::GlobalLock(emu),
        "GlobalReAlloc" => kernelbase::GlobalReAlloc(emu),
        "GlobalSize" => kernelbase::GlobalSize(emu),
        "GlobalUnlock" => kernelbase::GlobalUnlock(emu),
        "HeapAlloc" => kernelbase::HeapAlloc(emu),
        "HeapCreate" => kernelbase::HeapCreate(emu),
        "HeapDestroy" => kernelbase::HeapDestroy(emu),
        "HeapFree" => kernelbase::HeapFree(emu),
        "HeapReAlloc" => kernelbase::HeapReAlloc(emu),
        "HeapSetInformation" => kernelbase::HeapSetInformation(emu),
        "HeapSize" => kernelbase::HeapSize(emu),
        "InitializeEnclave" => kernelbase::InitializeEnclave(emu),
        "IsEnclaveTypeSupported" => kernelbase::IsEnclaveTypeSupported(emu),
        "LoadEnclaveData" => kernelbase::LoadEnclaveData(emu),
        "LocalFlags" => kernelbase::LocalFlags(emu),
        "LocalFree" => kernelbase::LocalFree(emu),
        "LocalReAlloc" => kernelbase::LocalReAlloc(emu),
        "LocalSize" => kernelbase::LocalSize(emu),
        "MapViewOfFile" => kernelbase::MapViewOfFile(emu),
        "MapViewOfFileEx" => kernelbase::MapViewOfFileEx(emu),
        "MapViewOfFileExNuma" => kernelbase::MapViewOfFileExNuma(emu),
        "MapViewOfFileFromApp" => kernelbase::MapViewOfFileFromApp(emu),
        "OfferVirtualMemory" => kernelbase::OfferVirtualMemory(emu),
        "PrefetchVirtualMemory" => kernelbase::PrefetchVirtualMemory(emu),
        "ReadProcessMemory" => kernelbase::ReadProcessMemory(emu),
        "ReclaimVirtualMemory" => kernelbase::ReclaimVirtualMemory(emu),
        "SetProcessWorkingSetSize" => kernelbase::SetProcessWorkingSetSize(emu),
        "UnmapViewOfFile" => kernelbase::UnmapViewOfFile(emu),
        "UnmapViewOfFileEx" => kernelbase::UnmapViewOfFileEx(emu),
        "VirtualAlloc" => kernelbase::VirtualAlloc(emu),
        "VirtualAllocEx" => kernelbase::VirtualAllocEx(emu),
        "VirtualAllocExNuma" => kernelbase::VirtualAllocExNuma(emu),
        "VirtualFree" => kernelbase::VirtualFree(emu),
        "VirtualFreeEx" => kernelbase::VirtualFreeEx(emu),
        "VirtualLock" => kernelbase::VirtualLock(emu),
        "VirtualProtect" => kernelbase::VirtualProtect(emu, addr),
        "VirtualProtectEx" => kernelbase::VirtualProtectEx(emu),
        "VirtualQuery" => kernelbase::VirtualQuery(emu, addr),
        "VirtualQueryEx" => kernelbase::VirtualQueryEx(emu),
        "WriteProcessMemory" => kernelbase::WriteProcessMemory(emu),
    },
        handled(()) => true,
        fallback => false,
    )
}
