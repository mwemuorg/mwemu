#[test]
fn shift_by_a_zero_count_keeps_the_flags() {
    let e = run(SHL_CL_ZERO_KEEPS_FLAGS, |_| {});
    assert_eq!(e.regs().rax, 0x8000_0000_0000_0000);
    assert!(
        e.flags_snapshot().f_cf,
        "CF set by stc survives shl rax, cl=0"
    );
}

#[test]
fn shift_by_one_overflow_rule() {
    let e = run(SHL_ONE_OF, |_| {});
    assert_eq!(
        e.regs().rbx,
        0x0100,
        "0xc0000000 << 1: OF=0 (sign kept), CF=1"
    );
    assert_eq!(
        e.regs().rcx,
        0x0001,
        "0x40000000 << 1: OF=1 (sign changed), CF=0"
    );
}

#[test]
fn shr_and_sar_carry_and_sign_fill() {
    let e = run(SHR_SAR, |_| {});
    assert_eq!(e.regs().rax, 0x1000_0001);
    assert_eq!(
        e.regs().rbx,
        0x0001,
        "shr: last bit out set; sar 63: last bit out clear"
    );
    assert_eq!(e.regs().rdx, u64::MAX, "sar fills with the sign");
    assert_eq!(e.regs().rsi, u64::MAX, "count 65 is masked to 1");
}

#[test]
fn rotates_with_and_without_carry() {
    let e = run(ROTATES, |_| {});
    assert_eq!(
        e.regs().rax,
        0x4123,
        "al was 0x03 after rol, then ax = ror ax, 4"
    );
    assert_eq!(e.regs().rbx, 0x0101, "rol: CF=1 and OF=1");
    assert_eq!(e.regs().rcx, 0x4123, "ror ax, 4");
    assert_eq!(
        e.regs().rdx,
        1,
        "rcl edx, 1 pulls CF in and pushes bit 31 out"
    );
    assert_eq!(e.regs().rsi, 0x8000_0000_0000_0000, "rcr rsi, 1 with CF=1");
    assert_eq!(e.regs().r8, 0x5a, "rcl r8b, 9 is a full 9-bit rotation");
    assert_eq!(e.regs().r9, 1);
}

#[test]
fn double_precision_shifts() {
    let e = run(SHLD_SHRD, |_| {});
    assert_eq!(e.regs().rax, 0x2345_6789_0abc_deff);
    assert_eq!(e.regs().rcx, 1, "shld: last bit shifted out of rax");
    assert_eq!(e.regs().rdx, 0x0112_3456);
}

#[test]
fn bit_test_register_forms() {
    let e = run(BIT_TEST_REGISTERS, |_| {});
    assert_eq!(
        e.regs().rax,
        0x40,
        "bts eax, 70 uses bit 6 and zero-extends"
    );
    assert_eq!(e.regs().rbx, 0x0101, "bt 63 and btr both saw a set bit");
    assert_eq!(e.regs().rdx, u64::MAX, "btr then btc restore the bit");
}

#[test]
fn bit_scans() {
    let e = run(BIT_SCANS, |_| {});
    assert_eq!(e.regs().rax, 12, "bsf");
    assert_eq!(e.regs().rcx, 31, "bsr");
    assert_eq!(e.regs().r8, 1, "bsf of zero sets ZF");
}

#[test]
fn popcnt_tzcnt_lzcnt() {
    let e = run(POPCNT_TZCNT_LZCNT, |_| {});
    assert_eq!(e.regs().rax, 32);
    assert_eq!(e.regs().rcx, 32, "tzcnt of 0 is the operand size");
    assert_eq!(e.regs().r8, 1, "and sets CF");
    assert_eq!(e.regs().rdx, 63);
}

#[test]
fn bswap_both_widths() {
    let e = run(BSWAP, |_| {});
    assert_eq!(e.regs().rax, 0x7856_3412, "32-bit bswap zero-extends");
    assert_eq!(e.regs().rbx, 0x0807_0605_0403_0201);
}

#[test]
fn logic_instruction_flags() {
    let e = run(LOGIC_FLAGS, |_| {});
    assert_eq!(e.regs().rax, 0);
    assert_eq!(e.regs().rbx, 0x0001, "xor eax, eax: ZF=1 and CF cleared");
    assert_eq!(e.regs().rcx, 1, "test cl, 0x80 sets SF");
    assert_eq!(e.regs().rdx, u64::MAX, "not");
}

#[test]
fn xchg_and_xadd() {
    let e = run(XCHG_XADD, |_| {});
    assert_eq!((e.regs().rax, e.regs().rbx), (2, 1));
    assert_eq!(
        (e.regs().rcx, e.regs().rdx),
        (15, 10),
        "xadd: sum in dest, old dest in src"
    );
}

#[test]
fn cmpxchg_register_forms() {
    let e = run(CMPXCHG_REGISTERS, |_| {});
    assert_eq!(e.regs().rbx, 9, "equal: destination takes the source");
    assert_eq!(
        e.regs().rax,
        100,
        "not equal: accumulator takes the destination"
    );
    assert_eq!(e.regs().rdx, 0x0001, "ZF set then clear");
}

#[test]
fn lea_addressing_forms() {
    let e = run(LEA_FORMS, |_| {});
    assert_eq!(e.regs().rax, 0x1090, "base + index*8 + disp");
    assert_eq!(e.regs().rdx, 0x4fff, "32-bit address size: ebx*5 - 1");
    assert_eq!(e.regs().rsi, 0x23, "index*2 + disp, no base");
    assert_eq!(
        e.regs().rdi,
        e.cfg.code_base_addr + 0x27,
        "rip-relative points past the lea"
    );
}
