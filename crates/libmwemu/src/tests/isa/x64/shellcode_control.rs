#[test]
fn loop_sums_one_to_one_hundred() {
    let e = run(LOOP_SUM, |_| {});
    assert_eq!(e.regs().rax, 5050);
    assert_eq!(e.regs().rcx, 0);
}

#[test]
fn recursive_factorial_keeps_the_stack_balanced() {
    let mut e = prepare(FACTORIAL_RECURSIVE, |_| {});
    let rsp = e.regs().rsp;
    e.run(None).unwrap();
    assert_eq!(e.regs().rax, 120, "5!");
    assert_eq!(e.regs().rdi, 5, "the pushes restored rdi at every level");
    assert_eq!(e.regs().rsp, rsp);
}

#[test]
fn setcc_signed_versus_unsigned_compare() {
    let e = run(SETCC_SIGNED_UNSIGNED, |_| {});
    assert_eq!(e.regs().rcx, 1, "setl: -1 < 1");
    assert_eq!(e.regs().rdx, 0, "setb: 0xffffffff is not below 1");
    assert_eq!(e.regs().rsi, 0, "setg");
    assert_eq!(e.regs().rdi, 1, "seta");
    assert_eq!(e.regs().r8, 1, "setle");
    assert_eq!(e.regs().r9, 0, "setbe");
}

/// Every not-taken `jcc` sets one bit of rbx, so rbx encodes the sixteen
/// decisions for the flags loaded from rax.
fn jcc_decisions(flags: u64) -> u64 {
    run(JCC_TABLE, |emu| emu.regs_mut().rax = flags).regs().rbx
}

#[test]
fn every_conditional_jump_with_all_flags_clear() {
    assert_eq!(
        jcc_decisions(0),
        0x5555,
        "jo jb je jbe js jp jl jle fall through"
    );
}

#[test]
fn every_conditional_jump_with_cf_pf_zf_sf_of_set() {
    assert_eq!(
        jcc_decisions(0x8c5),
        0x9aaa,
        "jno jae jne ja jns jnp jl jg fall through"
    );
}

/// `cmovo cmovb cmove cmovbe cmovs cmovp cmovl cmovle` packed MSB-first into rdx.
fn cmov_decisions(flags: u64) -> u64 {
    run(CMOV_TABLE, |emu| emu.regs_mut().rax = flags).regs().rdx
}

#[test]
fn conditional_moves_follow_the_flags() {
    assert_eq!(cmov_decisions(0), 0, "nothing moves with the flags clear");
    assert_eq!(cmov_decisions(0x8c5), 0xfd, "all but cmovl (SF == OF)");
    assert_eq!(cmov_decisions(0x80), 0x0b, "SF alone: cmovs, cmovl, cmovle");
}

#[test]
fn indirect_jump_ret_as_jump_and_ret_imm() {
    let mut e = prepare(JMP_INDIRECT_AND_RET_IMM, |_| {});
    let rsp = e.regs().rsp;
    e.run(None).unwrap();
    assert_eq!(
        e.regs().rbx,
        2,
        "jmp rax skipped mov 1; push/ret skipped mov 3"
    );
    assert_eq!(e.regs().rdx, 7, "the call reached its target");
    assert_eq!(e.regs().rsp, rsp + 8, "ret 8 popped eight extra bytes");
}

#[test]
fn jrcxz_and_push_pop_balance() {
    let e = run(JRCXZ_AND_STACK_BALANCE, |_| {});
    assert_eq!(e.regs().rax, 0, "jrcxz taken with rcx = 0");
    assert_eq!(e.regs().rbx, 2, "not taken with rcx = 1");
    assert_eq!(
        (e.regs().rdx, e.regs().rdi),
        (2, 0),
        "pops in reverse order"
    );
    assert_eq!(e.regs().rsi, 0, "rsp is back where it started");
}

#[test]
fn push_immediate_sign_extension() {
    let e = run(PUSH_IMM_SIGN, |_| {});
    assert_eq!(e.regs().rax, u64::MAX, "push -1 (imm8)");
    assert_eq!(e.regs().rbx, 0x7f);
    assert_eq!(e.regs().rcx, 0x1234_5678, "push imm32");
    assert_eq!(e.regs().rdx, 0xffff_ffff_ffff_ff80, "push -128");
}

#[test]
fn sahf_lahf_cmc_stc_clc() {
    let e = run(FLAG_INSTRUCTIONS, |_| {});
    assert_eq!(e.regs().rbx & 0xff, 1, "sahf loaded CF");
    assert_eq!(e.regs().rcx & 0xff, 1, "ZF");
    assert_eq!(e.regs().rdx & 0xff, 1, "SF");
    assert_eq!(e.regs().rsi & 0xff, 1, "PF");
    assert_eq!(e.regs().r8, 0xd700, "lahf: 0xd5 plus the always-set bit 1");
    assert_eq!(e.regs().r9, 0, "stc; cmc clears CF");
    assert_eq!(e.regs().r10, 0, "clc");
}
