#[test]
fn clone_creates_thread_futex_blocks_and_wakes_exit_ends_only_child() {
    let emu = run_linux(CLONE_FUTEX);
    let base = code_base(&emu);
    assert_eq!(
        emu.regs().r13 as i64,
        -11,
        "futex_wait on a changed word is EAGAIN"
    );
    assert_eq!(emu.threads.len(), 2, "clone added one thread");
    let child_tid = emu.threads[1].id;
    assert_eq!(emu.regs().rbx, child_tid, "parent got the child's tid");
    assert_eq!(emu.regs().r14, child_tid, "CLONE_CHILD_SETTID stored it");
    assert_eq!(
        emu.regs().r12,
        0x1234,
        "parent saw the child's write after the futex wake"
    );
    assert!(emu.threads[1].suspended, "exit() retired the child only");
    assert_eq!(
        emu.maps.read_dword(base + 0xfa),
        Some(0),
        "CLONE_CHILD_CLEARTID zeroed ctid at exit, which is what released the join"
    );
    assert!(!emu.threads[0].suspended, "the parent reached exit_group");
    assert_eq!(emu.regs().rdi, 0, "exit_group(0)");
}

