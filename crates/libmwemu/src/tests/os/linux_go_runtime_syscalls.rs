#[test]
fn epoll_eventfd_pipe_pseudo_fds_and_clock_gettime() {
    let emu = run_linux(POLL_TIME);
    let base = code_base(&emu);
    let (ep, efd) = (emu.regs().rbx, emu.regs().r12);
    assert!(
        ep >= 3 && efd >= 3 && ep != efd,
        "epoll and eventfd got distinct fds"
    );
    assert_eq!(emu.regs().r13, 0, "epoll_ctl ADD");
    assert_eq!(emu.regs().r14, 0, "epoll_pwait reports no events");
    assert_eq!(emu.regs().r15, 0, "pipe2");
    let (r, w) = (
        emu.maps.read_dword(base + 0x179).unwrap(),
        emu.maps.read_dword(base + 0x17d).unwrap(),
    );
    assert!(r >= 3 && w >= 3 && r != w, "pipe ends are distinct fds");
    assert_eq!(
        emu.maps.read_qword(base + 0x181),
        Some(4),
        "write to the pipe is swallowed whole"
    );
    assert_eq!(
        emu.maps.read_qword(base + 0x189),
        Some(0),
        "read from the pipe is EOF"
    );
    assert_eq!(
        emu.maps.read_qword(base + 0x191),
        Some(0),
        "clock_gettime ok"
    );
    assert_eq!(
        emu.maps.read_qword(base + 0x199),
        Some(0),
        "close(epoll fd) ok"
    );
    let mono_ns = emu.maps.read_qword(base + 0x1a1 + 8).unwrap();
    let real_s = emu.maps.read_qword(base + 0x1b1).unwrap();
    assert!(mono_ns < 1_000_000_000, "tv_nsec in range");
    assert!(
        real_s > 1_600_000_000,
        "CLOCK_REALTIME is the host wall clock"
    );
}
