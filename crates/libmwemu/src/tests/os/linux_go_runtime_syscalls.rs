#[test]
fn mmap_page_semantics_reservations_and_fixed_remap() {
    let emu = run_linux(MMAP_PAGES);
    let (a, b, c, d, e) = (
        emu.regs().rbx,
        emu.regs().r12,
        emu.regs().r13,
        emu.regs().r14,
        emu.regs().r15,
    );
    assert_eq!(a & 0xfff, 0, "mmap result is page aligned");
    assert!(
        emu.maps.is_mapped(a + 0x10fff),
        "length rounded up to 0x11000"
    );
    assert_ne!(b, a + 0x10c10, "unaligned hint ignored");
    assert_eq!(b & 0xfff, 0, "result page aligned despite the hint");
    assert!(emu.maps.is_mapped(b) && emu.maps.is_mapped(b + 0xfffff));
    assert_eq!(c & 0xfff, 0);
    assert!(
        d < c || d >= c + 0x2000_0000,
        "a later mapping (0x{d:x}) must not land inside the 512 MiB reservation at 0x{c:x}"
    );
    assert_eq!(
        e,
        a + 0x1000,
        "MAP_FIXED into the munmap'ed hole lands exactly there"
    );
    assert_eq!(emu.maps.read_dword(e), Some(0xcafe));
    assert!(
        emu.maps.is_mapped(a) && emu.maps.is_mapped(a + 0x2000),
        "neighbours kept"
    );
}

