#[test]
fn vfork_execve_is_logged_child_retired_parent_waits() {
    helpers::setup();
    let mut emu = emu64();
    emu.os = crate::arch::OperatingSystem::Linux;
    emu.max_pos = Some(100_000);
    emu.load_code_bytes(VFORK_EXEC);
    let seen = Rc::new(RefCell::new(Vec::new()));
    let sink = Rc::clone(&seen);
    emu.hooks.on_syscall(move |emu, nr| {
        if nr == 59 {
            sink.borrow_mut().push(emu.maps.read_string(emu.regs().rdi));
        }
        true
    });
    let _ = emu.run(None);
    assert!(emu.pos < 100_000, "snippet did not reach exit_group");
    assert_eq!(
        *seen.borrow(),
        vec!["/bin/true".to_string()],
        "execve reached the gateway once"
    );
    assert_eq!(emu.threads.len(), 2);
    let child = emu.threads[1].id;
    assert_eq!(
        emu.regs().rbx,
        child,
        "vfork returned the child pid to the parent"
    );
    assert_eq!(emu.regs().r12, child, "wait4 returned the child pid");
    assert_eq!(emu.regs().r13, 0, "wait4 status: exited 0");
    assert!(
        emu.threads[1].suspended,
        "the child was retired at execve, not at its exit(7)"
    );
    assert_eq!(emu.regs().rdi, 0, "parent's exit_group(0)");
}

