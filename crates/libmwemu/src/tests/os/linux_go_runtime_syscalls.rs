//! Linux x64 syscall semantics the Go runtime depends on, exercised with
//! hand-assembled snippets (nasm source in the comments, bytes inline) so
//! nothing needs a sample bundle: mmap/munmap page semantics and reservations,
//! clone + futex + per-thread exit, vfork + execve + wait4, and the netpoll
//! fds (epoll, eventfd, pipe) plus clock_gettime.

use crate::tests::helpers;
use crate::*;
use std::cell::RefCell;
use std::rc::Rc;

/// Run raw x64 code as a Linux process until exit_group; returns the emu.
fn run_linux(code: &[u8]) -> emu::Emu {
    helpers::setup();
    let mut emu = emu64();
    emu.os = crate::arch::OperatingSystem::Linux;
    emu.max_pos = Some(100_000);
    emu.load_code_bytes(code);
    let _ = emu.run(None);
    assert!(
        emu.pos < 100_000,
        "snippet did not reach exit_group (pos {})",
        emu.pos
    );
    emu
}

fn code_base(emu: &emu::Emu) -> u64 {
    emu.cfg.code_base_addr
}

